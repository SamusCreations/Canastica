export function getIsoDaysAgo(days: number, baseDateStr = '2026-10-24'): string {
  const d = new Date(`${baseDateStr}T12:00:00`);
  d.setDate(d.getDate() - days);
  return d.toISOString().slice(0, 10);
}

export function getIsoDaysFromNow(days: number, baseDateStr = '2026-10-24'): string {
  const d = new Date(`${baseDateStr}T12:00:00`);
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0, 10);
}

